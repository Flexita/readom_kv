"""Build the handoff module (handoff/) for one profile (profiles/*.json), in the build VM.

The module pins what the build makes and nothing the device has: the kernel,
the public initramfs, the command line, which ATAGs may be passed, and the
physical plan. The device's ATAGs and its archive (boot/devicedata) are made
on the device at each start and checked by the module against these rules.

Usage: build_module.py PROFILE --kernel ZIMAGE --public-initramfs FILE --cmdline TEXTFILE --output DIR
"""
import argparse, hashlib, importlib.util, json, os, platform, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = ['stage.c', 'stage_abi.h', 'native-abi.h', 'engine-guard.h', 'identity-attrs.h', 'allocation-ranges.h',
           'native-handoff.h', 'pw3_plan.c', 'pw3_plan.h', 'sha256.c', 'sha256.h', 'backend.c', 'backend.h',
           'transition.S', 'transition_abi.h', 'cache-ops.S', 'stack.S', 'qemu-pm.c']
TOOLS = '/home/builder/toolchains/aosp-arm-gcc49/bin/'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def c_bytes(hexdigest):
    return '{' + ','.join(str(b) for b in bytes.fromhex(hexdigest)) + '}'


def c_string(text):
    assert all(32 <= ord(c) < 127 and c not in '"\\' for c in text)
    return '"' + text + '"'


def ranges(name, rows):
    body = ','.join('{%#xu,%#xu}' % (int(a, 0), int(b, 0)) for a, b in rows)
    return 'static const struct pw_range %s[]={%s};\n' % (name, body)


def target_lock(profile, kernel, public, cmdline, footprint):
    p = profile
    out = ['/* Generated by boot/build_module.py; what this build pins. */',
           '#ifndef PW3_TARGET_LOCK_H', '#define PW3_TARGET_LOCK_H',
           '#define TARGET_MACHINE %du' % p['machine'],
           '#define TARGET_IDENTITY_LIMIT %#xu' % int(p['identity_limit'], 0),
           '#define TARGET_FOOTPRINT_END %#xu' % footprint['end'],
           '#define TARGET_KERNEL_BYTES %du' % len(kernel),
           'static const u8 target_kernel_sha256[32]=%s;' % c_bytes(sha(kernel)),
           '#define TARGET_PUBLIC_INITRAMFS_BYTES %du' % len(public),
           'static const u8 target_public_initramfs_sha256[32]=%s;' % c_bytes(sha(public)),
           '#define TARGET_DEVICE_ARCHIVE_MAX %du' % p['device_archive_max'],
           'static const char target_cmdline[]=%s;' % c_string(cmdline),
           'static const u32 target_atag_kinds[]={%s};' % ','.join('%#xu' % int(k, 0) for k in p['atag_kinds'])]
    lock = '\n'.join(out) + '\n'
    lock += ranges('target_ram', p['ram']) + ranges('target_forbidden', p['forbidden'])
    lock += ranges('target_footprint', [[hex(footprint['start']), hex(footprint['bytes'])]])
    functions = p.get('stock_functions')
    if functions:
        show = functions['pm_test_show']
        lock += '#define TARGET_PM_SHOW_BYTES %du\nstatic const u8 target_pm_show_sha256[32]=%s;\n' % (show['bytes'], c_bytes(show['sha256']))
        names = ['l2x0_flush_all', 'l2x0_disable', 'l2x0_inv_all']
        lock += 'static const char *const target_outer_names[3]={%s};\n' % ','.join('"%s"' % n for n in names)
        lock += 'static const u32 target_outer_bytes[3]={%s};\n' % ','.join('%du' % functions[n]['bytes'] for n in names)
        lock += 'static const u8 target_outer_sha256[3][32]={%s};\n' % ','.join(c_bytes(functions[n]['sha256']) for n in names)
    return lock + '#endif\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('profile', type=Path)
    ap.add_argument('--kernel', type=Path, required=True)
    ap.add_argument('--public-initramfs', type=Path, required=True)
    ap.add_argument('--cmdline', type=Path, required=True)
    ap.add_argument('--output', type=Path, required=True)
    a = ap.parse_args()
    if platform.node() != 'lima-pw3' or os.geteuid() == 0:
        sys.exit('Run as the builder in the build VM (tools/vm.sh shell).')
    profile = json.loads(a.profile.read_text())
    spec_v = importlib.util.spec_from_file_location('voyage_profile', HERE.parent / 'tools/voyage_profile.py')
    voyage_profile = importlib.util.module_from_spec(spec_v)
    spec_v.loader.exec_module(voyage_profile)
    voyage_profile.refuse_unless_installable(a.profile)
    kernel, public = a.kernel.read_bytes(), a.public_initramfs.read_bytes()
    cmdline = a.cmdline.read_text().rstrip('\n')
    if kernel[0x24:0x28] != bytes.fromhex('18286f01'):
        sys.exit('not a zImage: ' + str(a.kernel))
    if public[:2] != b'\x1f\x8b':
        sys.exit('the public initramfs must be a gzip archive')
    if not cmdline or len(cmdline) >= 1024 or '\n' in cmdline:
        sys.exit('invalid command line')
    os.umask(0o022)
    a.output.mkdir(parents=True, exist_ok=False)
    # The decompressor's RAM footprint, from this kernel's own build files.
    subprocess.run([sys.executable, str(HERE / 'handoff/derive_kernel_footprint.py'), '--profile', profile['footprint_profile'],
                    '--output', str(a.output / 'footprint')], check=True, stdout=subprocess.DEVNULL)
    footprint = json.loads((a.output / 'footprint/footprint.json').read_text())
    if footprint['input_sha256']['arch/arm/boot/zImage'] != sha(kernel):
        sys.exit('the footprint is of another kernel than --kernel')
    envelope = footprint['page_rounded_envelope']
    work = Path('/home/builder/pw3-boot-module') / a.output.name
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    for name in SOURCES:
        shutil.copyfile(HERE / 'handoff' / name, work / name)
    (work / 'target-lock.h').write_text(target_lock(profile, kernel, public, cmdline, envelope))
    stock = profile['module_profile'] == 1
    make = 'obj-m := pw3_first_kernel.o' + ('' if stock else ' pw3_qemu_pm.o') + '\n'
    make += 'pw3_first_kernel-y := stage.o sha256.o pw3_plan.o backend.o transition.o cache-ops.o' + ('' if stock else ' stack.o') + '\n'
    if not stock:
        make += 'pw3_qemu_pm-y := qemu-pm.o\n'
    make += ('ccflags-y += -fno-pic -fno-pie -Werror -DPWS_PROFILE=%d -DPW3_CONTROLLED_HANDOFF -DPW3_TRANSITION_BUILD_FOR_REVIEW\n'
             'asflags-y += -DPW3_CONTROLLED_HANDOFF -DPW3_TRANSITION_BUILD_FOR_REVIEW\n') % profile['module_profile']
    (work / 'Makefile').write_text(make)
    command = ['make', '-C', profile['module_kernel_source'], 'O=' + profile['module_kernel_output'], 'ARCH=arm',
               'CROSS_COMPILE=' + TOOLS + 'arm-linux-androidkernel-', 'M=' + str(work), 'modules']
    with (a.output / 'build.log').open('w') as log:
        subprocess.run(command, stdout=log, stderr=subprocess.STDOUT, check=True)
    modules = ['pw3_first_kernel'] + ([] if stock else ['pw3_qemu_pm'])
    for name in modules:
        shutil.copyfile(work / (name + '.ko'), a.output / (name + '.ko'))
    shutil.copyfile(work / 'target-lock.h', a.output / 'target-lock.h')
    receipt = {
        'schema': 1, 'profile': profile.get('description'), 'profile_sha256': sha(a.profile.read_bytes()),
        'module_profile': profile['module_profile'],
        'kernel': {'bytes': len(kernel), 'sha256': sha(kernel)},
        'public_initramfs': {'bytes': len(public), 'sha256': sha(public)},
        'cmdline': cmdline, 'footprint': envelope,
        'sources_sha256': {n: sha((HERE / 'handoff' / n).read_bytes()) for n in SOURCES},
        'modules_sha256': {n: sha((a.output / (n + '.ko')).read_bytes()) for n in modules},
        'target_lock_sha256': sha((a.output / 'target-lock.h').read_bytes()),
        'contains_device_data': False,
    }
    (a.output / 'build-result.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps({k: receipt[k] for k in ['module_profile', 'modules_sha256', 'contains_device_data']}, indent=1))


if __name__ == '__main__':
    main()
